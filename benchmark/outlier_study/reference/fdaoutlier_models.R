# Run from the repository root: Rscript benchmark/outlier_study/reference/fdaoutlier_models.R
# References: R 4.5.1; fdaoutlier 0.2.1 (current CRAN, published 2023-09-30).
# https://cran.r-project.org/src/contrib/fdaoutlier_0.2.1.tar.gz
# Functions audited (R/simulation_models.R): covfunexp, determine,
# simulation_model1 ... simulation_model9 (the commented-out oscillating
# model 9 in that file is not exported and not used).
#
# Golden values for the outlier-study generators in ../common.jl. The
# Gaussian process is switched off (cov_alpha = cov_alpha2 = 1e-30, noise SD
# 1e-15), so each curve is its deterministic part. The random parameters of
# each curve (signs, onsets, phases, amplitudes) are recovered by replaying
# fdaoutlier's RNG draws from the same seed in the same order; the script
# checks that the documented model formulas with these parameters reproduce
# fdaoutlier's output before writing them. The covariance file stores
# covfunexp on five points for the three covariances the models use.
# CI does not run R; check.jl reads the committed CSVs.
suppressMessages(library(fdaoutlier))
stopifnot(packageVersion("fdaoutlier") == "0.2.1")

n <- 6L; p <- 50L; rate <- 0.5; tiny <- 1e-30; seed <- 20261027L
tt <- seq(0, 1, length.out = p)
no <- round(n * rate)

prefix <- function(s) {          # e <- rnorm(n*p); determine(TRUE, n, rate)
  set.seed(s)
  invisible(rnorm(n * p))
  sort(sample(1:n, no))
}

rows <- list()
add <- function(model, out, y, params) {
  for (i in seq_len(n)) {
    pr <- c(params[[i]], rep(NA, 3 - length(params[[i]])))
    rows[[length(rows) + 1]] <<- c(model = model, curve = i, outlier = as.integer(i %in% out),
                                   p1 = pr[1], p2 = pr[2], p3 = pr[3], setNames(y[i, ], paste0("y", 1:p)))
  }
}
check <- function(y, expected) stopifnot(max(abs(y - expected)) < 1e-12)
none <- function() rep(list(numeric(0)), n)
write_csv <- function(x, path) {   # full precision, blank for unused parameters
  cells <- ifelse(is.na(x), "", sprintf("%.17g", x))
  write(paste(colnames(x), collapse = ","), path, append = TRUE)
  write(apply(matrix(cells, nrow(x)), 1, paste, collapse = ","), path, append = TRUE)
}

for (m in 1:9) {
  s <- seed + m
  args <- list(n = n, p = p, outlier_rate = rate, seed = s, cov_alpha = tiny)
  if (m == 5) args$cov_alpha2 <- tiny
  sim <- do.call(get(paste0("simulation_model", m)), args)
  y <- sim$data
  out <- prefix(s)
  stopifnot(identical(as.integer(out), as.integer(sim$true_outliers)))
  params <- none()
  expected <- matrix(4 * tt, n, p, byrow = TRUE)
  if (m %in% 1:3) {
    invisible(rnorm(p * no))
    k <- rbinom(no, 1, 0.5); k[k == 0] <- -1
    onset <- if (m == 1) rep(NA, no) else runif(no, 0.1, 0.9)
    for (j in seq_len(no)) {
      i <- out[j]
      params[[i]] <- c(k[j], onset[j])
      bump <- switch(m, rep(1, p), (tt >= onset[j]) * (tt <= onset[j] + 0.05), as.numeric(tt >= onset[j]))
      expected[i, ] <- 4 * tt + c(8, 8, 6)[m] * k[j] * bump
    }
  } else if (m == 4) {
    expected <- matrix(30 * tt * (1 - tt)^1.5, n, p, byrow = TRUE)
    for (i in out) expected[i, ] <- 30 * (1 - tt) * tt^1.5
  } else if (m == 6) {
    invisible(rnorm(p * no))
    u <- rbinom(no, 1, 0.5); v <- runif(no, 0.25, 0.75)
    for (j in seq_len(no)) {
      i <- out[j]
      params[[i]] <- c(u[j], v[j])
      expected[i, ] <- 4 * tt + (-1)^u[j] * 1.8 + (-1)^(1 - u[j]) * exp(-50 * (tt - v[j])^2) / sqrt(0.02 * pi)
    }
  } else if (m == 7) {
    invisible(rnorm(p * no))
    theta <- runif(no, 0.25, 0.75)
    for (j in seq_len(no)) {
      i <- out[j]
      params[[i]] <- theta[j]
      expected[i, ] <- 4 * tt + 2 * sin(4 * pi * (tt + theta[j]))
    }
  } else if (m == 8) {
    expected <- matrix(2 * sin(15 * pi * tt), n, p, byrow = TRUE)
    for (i in out) expected[i, ] <- 2 * sin(15 * pi * tt + 2)
  } else if (m == 9) {
    a1 <- runif(n, 3, 8); a2 <- runif(n, 3, 8)
    u <- sample(c(TRUE, FALSE), no, replace = TRUE, prob = c(0.5, 0.5))
    invisible(rnorm(p * sum(u))); invisible(rnorm(p * sum(!u)))
    c1 <- runif(sum(u), 9, 10.5); c2 <- runif(sum(u), 9, 10.5)
    b1 <- runif(sum(!u), 1.5, 2.5); b2 <- runif(sum(!u), 1.5, 2.5)
    for (i in seq_len(n)) params[[i]] <- c(a1[i], a2[i])
    params[out[u]] <- lapply(seq_len(sum(u)), function(j) c(c1[j], c2[j], 1))
    params[out[!u]] <- lapply(seq_len(sum(!u)), function(j) c(b1[j], b2[j], 0))
    tt2 <- seq(0, 2 * pi, length.out = p)
    for (i in seq_len(n)) expected[i, ] <- params[[i]][1] * sin(tt2) + params[[i]][2] * cos(tt2)
  }
  check(y, expected)
  add(m, out, y, params)
}

models <- do.call(rbind, rows)
header <- c("# fdaoutlier 0.2.1 simulation_model1..9 deterministic parts; R 4.5.1;",
            "# generated by benchmark/outlier_study/reference/fdaoutlier_models.R")
path <- "benchmark/outlier_study/reference/fdaoutlier_models.csv"
writeLines(header, path)
write_csv(models, path)

grid5 <- seq(0, 1, length.out = 5)
covs <- list(c(1, 1, 1), c(0.3, 1 / 0.3, 1), c(5, 2, 0.5))
cov_rows <- do.call(rbind, lapply(covs, function(a) {
  K <- fdaoutlier:::covfunexp(grid5, a[1], a[2], a[3])
  cbind(alpha = a[1], beta = a[2], nu = a[3], i = rep(1:5, 5), j = rep(1:5, each = 5), value = as.vector(K))
}))
path <- "benchmark/outlier_study/reference/fdaoutlier_covariances.csv"
writeLines(c("# fdaoutlier 0.2.1 covfunexp on seq(0, 1, length.out = 5); R 4.5.1;",
             "# generated by benchmark/outlier_study/reference/fdaoutlier_models.R"), path)
write_csv(cov_rows, path)
cat("Wrote fdaoutlier model and covariance goldens\n")
