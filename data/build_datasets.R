#!/usr/bin/env Rscript
# Reference sources: fda 6.3.0, fda.usc 2.2.0, refund 0.1-40 (source-lock.csv).
# Run from the repository root: Rscript data/build_datasets.R [source-cache]
# Base R only: read the data objects directly from the pinned package archives.
# Full exports go to ignored data/build/payload; identical subsets go to data/samples.
options(stringsAsFactors = FALSE)
script <- sub('^--file=', '', grep('^--file=', commandArgs(), value = TRUE)[1])
data_dir <- dirname(normalizePath(script))
args <- commandArgs(trailingOnly = TRUE)
cache <- if (length(args)) args[1] else file.path(data_dir, 'build', 'sources')
dir.create(cache, recursive = TRUE, showWarnings = FALSE)
lock <- read.csv(file.path(data_dir, 'source-lock.csv'), comment.char = '#')
packages <- list()
for (i in seq_len(nrow(lock))) {
    p <- lock[i, ]
    archive <- file.path(cache, paste0(p$package, '_', p$version, '.tar.gz'))
    if (!file.exists(archive)) {
        tryCatch(download.file(p$url, archive, mode = 'wb', quiet = TRUE),
            error = function(e) download.file(sub('/src/contrib/',
                paste0('/src/contrib/Archive/', p$package, '/'), p$url),
                archive, mode = 'wb', quiet = TRUE))
    }
    stopifnot(unname(tools::md5sum(archive)) == p$md5)
    untar(archive, exdir = cache)
    root <- file.path(cache, p$package)
    desc <- read.dcf(file.path(root, 'DESCRIPTION'))
    stopifnot(desc[1, 'Version'] == p$version)
    packages[[p$package]] <- list(root = root, version = p$version,
        license = unname(desc[1, 'License']), url = p$url, sha256 = p$sha256)
}

read_object <- function(package, object) {
    files <- list.files(file.path(packages[[package]]$root, 'data'), full.names = TRUE)
    f <- files[tools::file_path_sans_ext(basename(files)) == object]
    stopifnot(length(f) == 1)
    e <- new.env(parent = emptyenv())
    load(f, envir = e)
    e[[object]]
}

# Quote fields and preserve all binary64 digits. NA and NaN become the explicit
# missing token NA. The loader accepts this generated, single-line CSV dialect.
write_csv <- function(x, file) {
    x <- as.data.frame(x, check.names = FALSE)
    for (j in seq_along(x)) {
        if (is.numeric(x[[j]])) x[[j]] <- ifelse(is.na(x[[j]]), NA,
            sprintf('%.17g', x[[j]]))
    }
    cat('# Generated by data/build_datasets.R; fda 6.3.0; fda.usc 2.2.0; refund 0.1-40\n', file = file)
    suppressWarnings(write.table(x, file, sep = ',', quote = TRUE, na = 'NA',
        row.names = FALSE, col.names = TRUE, append = TRUE, eol = '\n'))
}

node <- function(name, values, grid, unit, grid_unit, kind = 'grid') {
    list(name = name, values = values, grid = grid, unit = unit,
        grid_unit = grid_unit, kind = kind)
}

