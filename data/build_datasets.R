export_set <- function(root, sample) {
    dir.create(root, recursive = TRUE, showWarnings = FALSE)
    reference <- list()
    for (name in names(specs)) {
        s <- specs[[name]]
        p <- packages[[s$package]]
        dir <- file.path(root, name)
        dir.create(dir, recursive = TRUE, showWarnings = FALSE)
        rows <- if (sample) s$sample else seq_len(nrow(s$covariates))
        cov <- s$covariates[rows, , drop = FALSE]
        stopifnot(!anyNA(cov$id), !anyDuplicated(cov$id))
        types <- vapply(cov, function(x) if (is.integer(x)) 'int' else if (is.numeric(x)) 'float' else 'string', '')
        write_csv(data.frame(column = names(cov), type = types), file.path(dir, 'schema.csv'))
        write_csv(cov, file.path(dir, 'covariates.csv'))
        write_csv(do.call(rbind, lapply(s$nodes, function(n) data.frame(name = n$name,
            kind = n$kind, unit = n$unit, grid_unit = n$grid_unit))), file.path(dir, 'components.csv'))
        metadata <- c(format_version = '1', name = name, package = s$package,
            package_version = p$version, object = s$object, url = p$url,
            source_sha256 = p$sha256, package_license = p$license,
            license = if (name == 'tecator') 'GPL-2; Tecator redistribution permission (see TECATOR.txt)' else 'GPL-2.0-or-later',
            description = s$description, citation = s$citation, notes = s$notes,
            nobs = length(rows), full_nobs = nrow(s$covariates), sample = tolower(as.character(sample)),
            source_rows = paste(rows, collapse = ';'), R_version = as.character(getRversion()))
        write_csv(data.frame(key = names(metadata), value = unname(metadata)), file.path(dir, 'metadata.csv'))
        file.copy(file.path(p$root, 'DESCRIPTION'), file.path(dir, 'SOURCE_DESCRIPTION'), overwrite = TRUE)
        file.copy(file.path(p$root, 'man', paste0(s$object, '.Rd')),
            file.path(dir, 'SOURCE_DOCUMENTATION.Rd'), overwrite = TRUE)
        file.copy(file.path(data_dir, 'licenses', 'GPL-2'), file.path(dir, 'LICENSE'), overwrite = TRUE)
        if (name == 'tecator') file.copy(file.path(data_dir, 'licenses', 'TECATOR.txt'),
            file.path(dir, 'TECATOR.txt'), overwrite = TRUE)
        for (n in s$nodes) {
            y <- n$values[rows, , drop = FALSE]
            stopifnot(all(is.finite(y[!is.na(y)])), all(is.finite(n$grid)), all(diff(n$grid) > 0))
            if (n$kind == 'grid') {
                write_csv(data.frame(time = n$grid), file.path(dir, paste0(n$name, '_grid.csv')))
                colnames(y) <- paste0('v', seq_len(ncol(y)))
                write_csv(data.frame(id = cov$id, y, check.names = FALSE), file.path(dir, paste0(n$name, '_values.csv')))
            } else {
                obs <- do.call(rbind, lapply(seq_len(nrow(y)), function(i) {
                    keep <- !is.na(y[i, ])
                    stopifnot(any(keep))
                    data.frame(id = cov$id[i], time = n$grid[keep], value = y[i, keep])
                }))
                write_csv(obs, file.path(dir, paste0(n$name, '_observations.csv')))
                write_csv(data.frame(time = range(n$grid)), file.path(dir, paste0(n$name, '_domain.csv')))
            }
            reference[[length(reference) + 1L]] <- data.frame(dataset = name, node = n$name,
                n = nrow(y), m = ncol(y), observed = sum(!is.na(y)), missing = sum(is.na(y)),
                sum_values = sum(y, na.rm = TRUE), sum_squares = sum(y^2, na.rm = TRUE),
                sum_grid = sum(n$grid), first_value = y[1, which(!is.na(y[1, ]))[1]])
        }
    }
    write_csv(do.call(rbind, reference), file.path(root, 'reference.csv'))
    # All payload files are data/notice text, including source DESCRIPTIONs.
    Sys.chmod(list.files(root, recursive = TRUE, full.names = TRUE), mode = '0644')
    Sys.chmod(list.dirs(root, full.names = TRUE), mode = '0755')
}

export_set(file.path(data_dir, 'build', 'payload'), FALSE)
